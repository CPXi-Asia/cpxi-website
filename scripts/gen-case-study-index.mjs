// Builds the case-study registry from whichever content files are present.
//
// Published case studies live in app/_content/case-studies/*.ts and are
// committed. Drafts pending client/naming review live in .../drafts/, which is
// gitignored (this repo is public), so production builds from git only ever
// see published entries, while local dev and CLI previews include drafts.
//
// Runs automatically before `npm run dev` and `npm run build`.
import fs from "node:fs";
import path from "node:path";

const root = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "app/_content/case-studies");
const draftsDir = path.join(dir, "drafts");
const out = path.join(dir, "registry.generated.ts");

const list = (d) =>
  fs.existsSync(d)
    ? fs.readdirSync(d).filter((f) => f.endsWith(".ts") && !f.includes(".generated."))
    : [];

const entries = [
  ...list(dir).map((f) => `./${f.replace(/\.ts$/, "")}`),
  ...list(draftsDir).map((f) => `./drafts/${f.replace(/\.ts$/, "")}`),
].sort();

const ident = (p) =>
  "cs_" + p.replace(/^\.\/(drafts\/)?/, "").replace(/[^a-zA-Z0-9]+/g, "_");

const body = `// GENERATED by scripts/gen-case-study-index.mjs. Do not edit.
import type { CaseStudy } from "../../_lib/case-studies";
${entries.map((p) => `import ${ident(p)} from "${p}";`).join("\n")}

export const CASE_STUDY_ENTRIES: CaseStudy[] = [
${entries.map((p) => `  ${ident(p)},`).join("\n")}
];
`;

fs.writeFileSync(out, body);
const drafts = list(draftsDir).length;
console.log(`case-study registry: ${entries.length - drafts} published, ${drafts} drafts`);
